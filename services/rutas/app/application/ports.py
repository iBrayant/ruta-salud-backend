"""Puertos (interfaces) que la capa de aplicación necesita del mundo exterior.

La infraestructura los implementa; los casos de uso solo conocen estas interfaces.
"""
from __future__ import annotations

from datetime import date
from typing import Any, Protocol

from ..domain.entities import ClimaVereda, Hospital, MatrizViaje, Vereda


class RepositorioVeredas(Protocol):
    def hospital(self) -> Hospital: ...
    def listar(self) -> list[Vereda]: ...
    def version(self) -> str: ...
    def detalle(self) -> list[dict[str, Any]]: ...


class ProveedorDistancias(Protocol):
    async def matriz(self, hospital: Hospital, veredas: list[Vereda]) -> MatrizViaje: ...


class ProveedorClima(Protocol):
    async def pronostico(self, veredas: list[Vereda], fecha: date, hora_inicio: int, hora_fin: int
                         ) -> dict[str, ClimaVereda] | None: ...


class RepositorioRutas(Protocol):
    async def siguiente_codigo(self, fecha: date) -> str: ...
    async def guardar(self, ruta: dict[str, Any]) -> None: ...
    async def obtener(self, ruta_id: str) -> dict[str, Any] | None: ...
    async def listar(self, limite: int, desplazamiento: int) -> list[dict[str, Any]]: ...
    async def ultima_visita(self, antes_de: date) -> dict[str, date]: ...
    async def marcar_ejecutada(self, ruta_id: str, usuario: str) -> dict[str, Any] | None: ...
    async def guardar_explicacion(self, ruta_id: str, explicacion: dict[str, Any]) -> None: ...


class ServicioExplicacion(Protocol):
    async def explicar(self, ruta: dict[str, Any]) -> dict[str, Any] | None: ...


class RegistroAuditoria(Protocol):
    async def registrar(self, accion: str, actor: Any, recurso: str, detalle: dict[str, Any], ip: str = ...
                        ) -> dict[str, Any]: ...
